CREATE SCHEMA exec;

CREATE TYPE exec.plan_run_status AS ENUM (
    'scheduled',
    'active',
    'cancelled',
    'completed'
);

CREATE TYPE exec.microcycle_classification AS ENUM (
    'normal',
    'deload',
    'reload'
);

CREATE TYPE exec.workout_session_status AS ENUM (
    'scheduled',
    'in_progress',
    'completed',
    'cancelled',
    'missed'
);

CREATE TYPE exec.completion_mode AS ENUM (
    'as_prescribed',
    'fallback'
);

CREATE TYPE exec.performance_status AS ENUM (
    'draft',
    'finalized'
);

CREATE TYPE exec.exercise_execution_mode AS ENUM (
    'as_prescribed',
    'substituted',
    'skipped',
    'additional'
);

CREATE TYPE exec.performed_set_status AS ENUM (
    'performed',
    'skipped'
);

CREATE TYPE exec.plan_run_event_type AS ENUM (
    'plan_revision_changed',
    'personal_record',
    'deload_started',
    'reload_started',
    'vacation',
    'training_break',
    'observation'
);

CREATE TABLE exec.plan_runs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    description text,
    initial_plan_revision_id integer NOT NULL
        REFERENCES plans.plan_revisions(id) ON DELETE RESTRICT,
    starts_on date NOT NULL,
    microcycle_count integer NOT NULL,
    microcycle_duration_days integer NOT NULL,
    ends_on date GENERATED ALWAYS AS (
        starts_on + (microcycle_count * microcycle_duration_days - 1)
    ) STORED,
    status exec.plan_run_status NOT NULL DEFAULT 'scheduled',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT plan_runs_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT plan_runs_microcycle_count_positive CHECK (microcycle_count > 0),
    CONSTRAINT plan_runs_microcycle_duration_positive CHECK (microcycle_duration_days > 0)
);

CREATE INDEX plan_runs_by_initial_revision
    ON exec.plan_runs (initial_plan_revision_id);
CREATE INDEX plan_runs_by_status_and_start
    ON exec.plan_runs (status, starts_on);

COMMENT ON COLUMN exec.plan_runs.microcycle_duration_days IS
    'Snapshot of the initial plan revision day count; used with starts_on and microcycle_count to derive ends_on.';

CREATE TABLE exec.microcycles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_run_id integer NOT NULL REFERENCES exec.plan_runs(id) ON DELETE CASCADE,
    ordinal integer NOT NULL,
    starts_on date NOT NULL,
    ends_on date NOT NULL,
    plan_revision_id integer NOT NULL
        REFERENCES plans.plan_revisions(id) ON DELETE RESTRICT,
    classification exec.microcycle_classification NOT NULL DEFAULT 'normal',
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT microcycles_ordinal_positive CHECK (ordinal > 0),
    CONSTRAINT microcycles_date_range_valid CHECK (ends_on >= starts_on),
    CONSTRAINT microcycles_plan_run_ordinal_unique UNIQUE (plan_run_id, ordinal),
    CONSTRAINT microcycles_plan_run_id_unique UNIQUE (plan_run_id, id)
);

CREATE INDEX microcycles_by_revision
    ON exec.microcycles (plan_revision_id, starts_on);

CREATE TABLE exec.workout_unit_tracks (
