CREATE TABLE exec.workout_sessions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_run_id integer NOT NULL,
    microcycle_id integer NOT NULL,
    workout_unit_track_id integer NOT NULL,
    source_plan_day_id integer NOT NULL
        REFERENCES plans.day_prescriptions(id) ON DELETE RESTRICT,
    source_plan_workout_unit_id integer NOT NULL
        REFERENCES plans.workout_unit_prescriptions(id) ON DELETE RESTRICT,
    fallback_source_plan_workout_unit_id integer
        REFERENCES plans.workout_unit_prescriptions(id) ON DELETE RESTRICT,
    scheduled_date date NOT NULL,
    status exec.workout_session_status NOT NULL DEFAULT 'scheduled',
    completion_mode exec.completion_mode,
    started_at timestamptz,
    completed_at timestamptz,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT workout_sessions_plan_run_microcycle_fk
        FOREIGN KEY (plan_run_id, microcycle_id)
        REFERENCES exec.microcycles(plan_run_id, id) ON DELETE CASCADE,
    CONSTRAINT workout_sessions_plan_run_track_fk
        FOREIGN KEY (plan_run_id, workout_unit_track_id)
        REFERENCES exec.workout_unit_tracks(plan_run_id, id) ON DELETE RESTRICT,
    CONSTRAINT workout_sessions_occurrence_unique
        UNIQUE (microcycle_id, workout_unit_track_id),
    CONSTRAINT workout_sessions_completion_state_valid CHECK (
        (status = 'completed' AND completion_mode IS NOT NULL)
        OR (status <> 'completed' AND completion_mode IS NULL)
    ),
    CONSTRAINT workout_sessions_timestamps_valid CHECK (
        (status = 'scheduled' AND started_at IS NULL AND completed_at IS NULL)
        OR (status = 'in_progress' AND started_at IS NOT NULL AND completed_at IS NULL)
        OR (
            status = 'completed'
            AND started_at IS NOT NULL
            AND completed_at IS NOT NULL
            AND completed_at >= started_at
        )
        OR (status IN ('cancelled', 'missed') AND started_at IS NULL AND completed_at IS NULL)
    ),
    CONSTRAINT workout_sessions_fallback_valid CHECK (
        (completion_mode = 'fallback' AND fallback_source_plan_workout_unit_id IS NOT NULL)
        OR (
            completion_mode IS DISTINCT FROM 'fallback'
            AND fallback_source_plan_workout_unit_id IS NULL
        )
    )
);

CREATE INDEX workout_sessions_calendar
    ON exec.workout_sessions (plan_run_id, scheduled_date, id);
CREATE INDEX workout_sessions_by_status
    ON exec.workout_sessions (plan_run_id, status, scheduled_date);

