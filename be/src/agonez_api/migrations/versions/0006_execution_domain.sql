CREATE VIEW exec.microcycle_trace AS
WITH session_summary AS (
    SELECT
        session.microcycle_id,
        count(*) AS scheduled_session_count,
        count(*) FILTER (WHERE session.status = 'completed') AS completed_session_count,
        count(*) FILTER (WHERE session.status = 'missed') AS missed_session_count,
        count(*) FILTER (WHERE session.status = 'cancelled') AS cancelled_session_count,
        count(*) FILTER (WHERE session.status = 'in_progress') AS in_progress_session_count
    FROM exec.workout_sessions AS session
    GROUP BY session.microcycle_id
), volume_summary AS (
    SELECT
        session.microcycle_id,
        sum(set_performance.load_kg * set_performance.repetitions) FILTER (
            WHERE set_performance.status = 'performed'
        ) AS performed_volume_load_kg
    FROM exec.workout_sessions AS session
    JOIN exec.workout_unit_prescriptions AS prescription
        ON prescription.workout_session_id = session.id
    JOIN exec.workout_unit_performances AS performance
        ON performance.workout_unit_prescription_id = prescription.id
    JOIN exec.exercise_unit_performances AS exercise_performance
        ON exercise_performance.workout_unit_performance_id = performance.id
    JOIN exec.set_performances AS set_performance
        ON set_performance.exercise_unit_performance_id = exercise_performance.id
    GROUP BY session.microcycle_id
)
SELECT
    run.id AS plan_run_id,
    microcycle.id AS microcycle_id,
    microcycle.ordinal,
    microcycle.starts_on,
    microcycle.ends_on,
    microcycle.plan_revision_id,
    revision.revision_no AS plan_revision_no,
    microcycle.classification,
    microcycle.notes,
    COALESCE(summary.scheduled_session_count, 0) AS scheduled_session_count,
    COALESCE(summary.completed_session_count, 0) AS completed_session_count,
    COALESCE(summary.missed_session_count, 0) AS missed_session_count,
    COALESCE(summary.cancelled_session_count, 0) AS cancelled_session_count,
    COALESCE(summary.in_progress_session_count, 0) AS in_progress_session_count,
    CASE
        WHEN COALESCE(summary.scheduled_session_count, 0) = 0 THEN NULL
        ELSE summary.completed_session_count::numeric / summary.scheduled_session_count
    END AS attendance_ratio,
    volume.performed_volume_load_kg
FROM exec.microcycles AS microcycle
JOIN exec.plan_runs AS run ON run.id = microcycle.plan_run_id
JOIN plans.plan_revisions AS revision ON revision.id = microcycle.plan_revision_id
LEFT JOIN session_summary AS summary ON summary.microcycle_id = microcycle.id
LEFT JOIN volume_summary AS volume ON volume.microcycle_id = microcycle.id;

