    CONSTRAINT workout_unit_tracks_key_not_blank CHECK (btrim(logical_key) <> ''),
    CONSTRAINT workout_unit_tracks_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT workout_unit_tracks_plan_run_key_unique UNIQUE (plan_run_id, logical_key),
