CREATE FUNCTION exec.enforce_session_performance_consistency()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_session_id integer;
    session_state exec.workout_session_status;
    artifact_state exec.performance_status;
BEGIN
    IF TG_TABLE_NAME = 'workout_sessions' THEN
        target_session_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
    ELSE
        SELECT prescription.workout_session_id
        INTO target_session_id
        FROM exec.workout_unit_prescriptions AS prescription
        WHERE prescription.id = CASE
            WHEN TG_OP = 'DELETE' THEN OLD.workout_unit_prescription_id
            ELSE NEW.workout_unit_prescription_id
        END;
    END IF;

    SELECT session.status
    INTO session_state
    FROM exec.workout_sessions AS session
    WHERE session.id = target_session_id;

    IF NOT FOUND THEN
        RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
    END IF;

    SELECT performance.status
    INTO artifact_state
    FROM exec.workout_unit_performances AS performance
    JOIN exec.workout_unit_prescriptions AS prescription
        ON prescription.id = performance.workout_unit_prescription_id
    WHERE prescription.workout_session_id = target_session_id;

    IF session_state = 'completed' AND artifact_state IS DISTINCT FROM 'finalized' THEN
        RAISE EXCEPTION
            'completed workout session % requires a finalized performance artifact',
            target_session_id;
    ELSIF session_state = 'in_progress' AND artifact_state IS DISTINCT FROM 'draft' THEN
        RAISE EXCEPTION
            'in-progress workout session % requires a draft performance artifact',
            target_session_id;
    ELSIF session_state IN ('scheduled', 'cancelled', 'missed') AND artifact_state IS NOT NULL THEN
        RAISE EXCEPTION
            'workout session % in state % cannot own a performance artifact',
            target_session_id,
            session_state;
    END IF;

    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE CONSTRAINT TRIGGER workout_sessions_performance_consistency
AFTER INSERT OR UPDATE OR DELETE ON exec.workout_sessions
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION exec.enforce_session_performance_consistency();

CREATE CONSTRAINT TRIGGER workout_performances_session_consistency
AFTER INSERT OR UPDATE OR DELETE ON exec.workout_unit_performances
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION exec.enforce_session_performance_consistency();

CREATE VIEW exec.workout_session_calendar AS
SELECT
    run.id AS plan_run_id,
    run.name AS plan_run_name,
    microcycle.id AS microcycle_id,
    microcycle.ordinal AS microcycle_ordinal,
    microcycle.plan_revision_id,
    revision.revision_no AS plan_revision_no,
    session.id AS workout_session_id,
    session.scheduled_date,
    session.status,
    session.completion_mode,
    track.id AS workout_unit_track_id,
    track.logical_key AS workout_unit_logical_key,
    track.name AS workout_unit_name,
    prescription.id AS workout_unit_prescription_id,
    performance.id AS workout_unit_performance_id,
    performance.status AS performance_status,
    session.started_at,
    session.completed_at,
    session.notes
FROM exec.workout_sessions AS session
JOIN exec.plan_runs AS run ON run.id = session.plan_run_id
JOIN exec.microcycles AS microcycle ON microcycle.id = session.microcycle_id
JOIN plans.plan_revisions AS revision ON revision.id = microcycle.plan_revision_id
JOIN exec.workout_unit_tracks AS track ON track.id = session.workout_unit_track_id
LEFT JOIN exec.workout_unit_prescriptions AS prescription
    ON prescription.workout_session_id = session.id
LEFT JOIN exec.workout_unit_performances AS performance
    ON performance.workout_unit_prescription_id = prescription.id;

CREATE VIEW exec.exercise_unit_trace AS
SELECT
    run.id AS plan_run_id,
    run.name AS plan_run_name,
    microcycle.ordinal AS microcycle_ordinal,
    session.scheduled_date,
    session.status AS session_status,
    session.completion_mode,
    workout_track.id AS workout_unit_track_id,
    workout_track.name AS workout_unit_name,
    exercise_track.id AS exercise_unit_track_id,
    exercise_track.logical_key AS exercise_unit_logical_key,
    exercise_track.name AS exercise_unit_name,
    prescription.source_plan_revision_id AS plan_revision_id,
    exercise_prescription.source_plan_exercise_variant_id
        AS prescribed_plan_exercise_variant_id,
    exercise_performance.actual_plan_exercise_variant_id
        AS performed_plan_exercise_variant_id,
    prescribed_exercise.id AS prescribed_exercise_id,
    prescribed_exercise.slug AS prescribed_exercise_slug,
    prescribed_exercise.name AS prescribed_exercise_name,
    actual_exercise.id AS performed_exercise_id,
    actual_exercise.slug AS performed_exercise_slug,
    actual_exercise.name AS performed_exercise_name,
    exercise_performance.execution_mode,
    set_prescription.ordinal AS prescribed_set_ordinal,
    set_performance.ordinal AS performed_set_ordinal,
    set_prescription.set_role_snapshot,
    set_prescription.rep_min AS prescribed_rep_min,
    set_prescription.rep_max AS prescribed_rep_max,
    set_prescription.target_rir,
    set_prescription.prescribed_load_kg,
    set_performance.status AS performed_set_status,
    set_performance.load_kg AS performed_load_kg,
    set_performance.repetitions AS performed_repetitions,
    set_performance.rir AS performed_rir,
    exercise_prescription.prescription_comment AS exercise_prescription_comment,
    set_prescription.prescription_comment AS set_prescription_comment,
    exercise_performance.performance_comment AS exercise_performance_comment,
    set_performance.performance_comment AS set_performance_comment,
    exercise_performance.engine_model_version,
    exercise_performance.etu_vector_snapshot,
    CASE
        WHEN exercise_performance.id IS NULL THEN NULL
        ELSE
            exercise_performance.execution_mode IS DISTINCT FROM 'as_prescribed'
            OR set_performance.prescribed_set_id IS NULL
            OR set_performance.status = 'skipped'
            OR set_performance.load_kg IS DISTINCT FROM set_prescription.prescribed_load_kg
    END AS diverged_from_prescription
FROM exec.set_prescriptions AS set_prescription
JOIN exec.exercise_unit_prescriptions AS exercise_prescription
    ON exercise_prescription.id = set_prescription.exercise_unit_prescription_id
JOIN exec.workout_unit_prescriptions AS prescription
    ON prescription.id = exercise_prescription.workout_unit_prescription_id
JOIN exec.workout_sessions AS session
    ON session.id = prescription.workout_session_id
JOIN exec.plan_runs AS run ON run.id = session.plan_run_id
JOIN exec.microcycles AS microcycle ON microcycle.id = session.microcycle_id
JOIN exec.workout_unit_tracks AS workout_track
    ON workout_track.id = session.workout_unit_track_id
JOIN exec.exercise_unit_tracks AS exercise_track
    ON exercise_track.id = exercise_prescription.exercise_unit_track_id
JOIN core.exercises AS prescribed_exercise
    ON prescribed_exercise.id = exercise_prescription.prescribed_exercise_id
LEFT JOIN exec.exercise_unit_performances AS exercise_performance
    ON exercise_performance.prescribed_exercise_unit_id = exercise_prescription.id
LEFT JOIN core.exercises AS actual_exercise
    ON actual_exercise.id = exercise_performance.actual_exercise_id
LEFT JOIN exec.set_performances AS set_performance
    ON set_performance.prescribed_set_id = set_prescription.id

UNION ALL

SELECT
    run.id AS plan_run_id,
    run.name AS plan_run_name,
    microcycle.ordinal AS microcycle_ordinal,
    session.scheduled_date,
    session.status AS session_status,
    session.completion_mode,
    workout_track.id AS workout_unit_track_id,
    workout_track.name AS workout_unit_name,
    exercise_track.id AS exercise_unit_track_id,
    exercise_track.logical_key AS exercise_unit_logical_key,
    exercise_track.name AS exercise_unit_name,
    prescription.source_plan_revision_id AS plan_revision_id,
    exercise_prescription.source_plan_exercise_variant_id
        AS prescribed_plan_exercise_variant_id,
    exercise_performance.actual_plan_exercise_variant_id
        AS performed_plan_exercise_variant_id,
    prescribed_exercise.id AS prescribed_exercise_id,
