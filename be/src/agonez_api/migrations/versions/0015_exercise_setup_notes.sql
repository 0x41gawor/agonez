CREATE TABLE exec.exercise_setup_notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_unit_track_id integer NOT NULL
        REFERENCES exec.exercise_unit_tracks(id) ON DELETE CASCADE,
    exercise_id integer NOT NULL REFERENCES core.exercises(id) ON DELETE RESTRICT,
    note_text text,
    rev integer NOT NULL DEFAULT 0,
    updated_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT exercise_setup_notes_slot_exercise_unique
        UNIQUE (exercise_unit_track_id, exercise_id),
    CONSTRAINT exercise_setup_notes_rev_nonnegative CHECK (rev >= 0),
    CONSTRAINT exercise_setup_notes_length_bounded
        CHECK (note_text IS NULL OR length(note_text) <= 2000),
    CONSTRAINT exercise_setup_notes_write_state_valid CHECK (
        (updated_at IS NULL AND rev = 0) OR (updated_at IS NOT NULL AND rev > 0)
    )
);

CREATE INDEX exercise_setup_notes_by_track
    ON exec.exercise_setup_notes (exercise_unit_track_id, exercise_id);

COMMENT ON TABLE exec.exercise_setup_notes IS
    'Standing "My setup" note per run-scoped slot and exercise: how the athlete sets a machine up, true until they change it. Unlike a performance comment it does not belong to one exposure. Rows are seeded empty when a plan run is created (prescribed exercise plus every plan variant of the slot) and created on first write for an Atlas substitute. A plan run never inherits notes from an earlier run.';

COMMENT ON COLUMN exec.exercise_setup_notes.note_text IS
    'The note; NULL or blank means the athlete has written nothing. Published as "text".';

COMMENT ON COLUMN exec.exercise_setup_notes.rev IS
    'Entity revision for optimistic concurrency, shared by the mobile op and the desktop endpoint. 0 means never written.';

COMMENT ON COLUMN exec.exercise_setup_notes.updated_at IS
    'NULL until the first write, so clients can tell "never written" from "cleared".';

INSERT INTO exec.exercise_setup_notes (exercise_unit_track_id, exercise_id)
SELECT DISTINCT exercise_track.id, variant.exercise_id
FROM exec.exercise_unit_tracks AS exercise_track
JOIN exec.workout_unit_tracks AS workout_track
  ON workout_track.id = exercise_track.workout_unit_track_id
JOIN exec.plan_runs AS run ON run.id = exercise_track.plan_run_id
JOIN plans.day_prescriptions AS day
  ON day.revision_id = run.initial_plan_revision_id
 AND 'day:' || day.ordinal::text = workout_track.logical_key
JOIN plans.workout_unit_prescriptions AS workout ON workout.day_id = day.id
JOIN plans.exercise_slots AS slot
  ON slot.workout_unit_id = workout.id
 AND 'slot:' || slot.ordinal::text = exercise_track.logical_key
JOIN plans.exercise_variants AS variant ON variant.slot_id = slot.id
ON CONFLICT ON CONSTRAINT exercise_setup_notes_slot_exercise_unique DO NOTHING;
